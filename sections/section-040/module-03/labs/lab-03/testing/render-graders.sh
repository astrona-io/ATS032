#!/usr/bin/env bash
# Author tool, run on your own machine (not on the VM, not by astrona).
#
# astrona runs every script of a QEMU lab by piping it into `bash` on the VM,
# with no other lab file next to it. The graders therefore carry their own
# copy of the checks. This script copies the block between the
# ">>> shared checks >>>" markers of validate.sh into:
#
#   validation/validate-<outcome>.sh   one grader per outcome
#   testing/verify-start.sh            every outcome must fail at the start
#   testing/wait-solved.sh             wait until every outcome passes
#
# Run it after every change to validate.sh:  bash testing/render-graders.sh
# Pass --check to fail (without writing) when a generated file is stale.
set -euo pipefail
lab_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
check_only=false
[ "${1:-}" = "--check" ] && check_only=true

shared=$(sed -n '/^# >>> shared checks >>>$/,/^# <<< shared checks <<<$/p' "$lab_dir/validate.sh")
[ -n "$shared" ] || { echo "no shared checks block in validate.sh" >&2; exit 1; }
outcomes=$(sed -n 's/^OUTCOMES="\(.*\)"$/\1/p' <<<"$shared")

header() {
  printf '#!/usr/bin/env bash\n'
  printf '# Generated by testing/render-graders.sh from validate.sh. Do not edit by hand.\n'
  printf '# %s\n' "$@"
  printf '# Runs on the lab VM as the astrona account (astrona pipes it into bash).\n\n'
}

stale=0
emit() {
  local target="$1" content="$2"
  if $check_only; then
    if [ "$(cat "$target" 2>/dev/null)" != "$content" ]; then
      echo "stale: ${target#"$lab_dir"/}" >&2
      stale=1
    fi
  else
    printf '%s\n' "$content" > "$target"
    chmod 0755 "$target"
  fi
}

mkdir -p "$lab_dir/validation" "$lab_dir/testing"

for outcome in $outcomes; do
  emit "$lab_dir/validation/validate-$outcome.sh" "$(
    header "Grades the outcome $outcome and prints one PASS: or FAIL: line."
    printf '%s\n\n' "$shared"
    printf 'main() {\n  grade %s\n}\n\nmain\n' "$outcome"
  )"
done

emit "$lab_dir/testing/verify-start.sh" "$(
  header "Run by astrona test before the reference solution: every outcome must" \
         "fail on the unfinished lab, with a grading result rather than a crash."
  printf '%s\n\n' "$shared"
  cat <<'EOF'
main() {
  local outcome output
  if ! output=$(lab_guard); then
    echo "$output"
    echo "FAIL: starting state: the guard rejected this VM"
    return 1
  fi
  for outcome in $OUTCOMES; do
    if output=$(grade "$outcome"); then
      echo "$output"
      echo "FAIL: starting state: $outcome passed on the unfinished lab"
      return 1
    fi
    if ! grep -q '^FAIL:' <<<"$output" || grep -q '^FAIL: Unknown outcome' <<<"$output"; then
      echo "$output"
      echo "FAIL: starting state: $outcome failed without a grading result"
      return 1
    fi
    echo "$outcome: $(grep -m1 '^FAIL:' <<<"$output")"
  done
  echo "PASS: every outcome fails on the unfinished lab"
}

main
EOF
)"

emit "$lab_dir/testing/wait-solved.sh" "$(
  header "Run by astrona test after the reference solution: wait, with a timeout," \
         "until the cluster settles and every outcome passes."
  printf '%s\n\n' "$shared"
  cat <<'EOF'
main() {
  local attempt outcome line all_passed
  local -a lines
  for attempt in $(seq 1 60); do
    all_passed=true
    lines=()
    for outcome in $OUTCOMES; do
      line=$(grade "$outcome") || all_passed=false
      lines+=("$line")
    done
    if $all_passed; then
      printf '%s\n' "${lines[@]}"
      echo "PASS: the reference solution settled (attempt $attempt)"
      return 0
    fi
    sleep 5
  done
  printf '%s\n' "${lines[@]}"
  echo "FAIL: the reference solution did not pass within five minutes"
  return 1
}

main
EOF
)"

if $check_only; then
  [ "$stale" -eq 0 ] && echo "generated graders are up to date"
  exit "$stale"
fi
echo "rendered graders for: $outcomes"
